async function test(model) {
  const base64 = getTestBase64()
  // HF router image classification: gửi base64 trong JSON { inputs: "..." }
  const res = await fetch(`${BASE}/${model}`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ inputs: base64 }),
    signal: AbortSignal.timeout(30000),
  })
  const body = await res.text()
  const preview = body.slice(0, 200)
  if (res.status === 401) console.log(`❌ [${model}] Key không hợp lệ`)
  else if (res.status === 503) console.log(`⏳ [${model}] Model đang load (cold start) — key OK`)
  else if (res.status === 200) console.log(`✅ [${model}] OK | ${preview}`)
  else console.log(`⚠️  [${model}] HTTP ${res.status} | ${preview}`)
}

